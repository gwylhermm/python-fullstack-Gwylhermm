"""
Calculadora de área de terreno retangular.

Armazena a largura e o comprimento de um terreno, calcula a área
(larguracomprimento) e exibe o resultado em metros quadrados.
"""

# Largura do terreno em metros (float)
largura = 12.5

# Comprimento do terreno em metros (float)
comprimento = 30.0

# Área do retângulo: largura multiplicada pelo comprimento
area = largura * comprimento

# Exibe o resultado no formato pedido
print(f"Área do terreno: {area} m²")